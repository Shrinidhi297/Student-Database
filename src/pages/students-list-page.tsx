const statusStyles: Record<StudentStatus, 'default' | 'secondary' | 'success' | 'muted'> = {
  active: 'success',
  inactive: 'secondary',
  graduated: 'default',
};

function exportToCSV(students: Student[]) {
  const headers = [
    'USN', 'First Name', 'Last Name', 'Email', 'Phone', 'Department',
    'Semester', 'Status', 'Grade Level', 'Attendance', 'Marks', 'GPA',
    'Enrollment Date', 'Notes',
  ];

  const rows = students.map((s) => [
    s.usn ?? '', s.first_name, s.last_name, s.email ?? '', s.phone ?? '',
    s.department ?? '', s.semester ?? '', s.status, s.grade_level ?? '',
    s.attendance ?? '', s.marks ?? '', s.gpa ?? '',
    format(new Date(s.enrollment_date), 'yyyy-MM-dd'), s.notes ?? '',
  ]);

  const csv = [headers.join(','), ...rows.map((r) => r.map((v) => `"${String(v).replace(/"/g, '""')}"`).join(','))].join('\n');

  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `students_${format(new Date(), 'yyyy-MM-dd')}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

function exportToJSON(students: Student[]) {
  const data = students.map(({ created_at, updated_at, user_id, ...rest }) => rest);
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `students_${format(new Date(), 'yyyy-MM-dd')}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

function exportToPDF(students: Student[]) {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });

  const title = `Student Records - ${format(new Date(), 'MMM d, yyyy')}`;
  doc.setFontSize(16);
  doc.text(title, 14, 15);
  doc.setFontSize(9);
  doc.text(`Total: ${students.length} students`, 14, 22);

  const headers = [
    'USN', 'First Name', 'Last Name', 'Email', 'Phone', 'Department',
    'Sem', 'Status', 'Grade', 'Attend.', 'Marks', 'GPA', 'Enrolled',
  ];

  const body = students.map((s) => [
    s.usn ?? '', s.first_name, s.last_name, s.email ?? '', s.phone ?? '',
    s.department ?? '', s.semester ?? '', s.status, s.grade_level ?? '',
    s.attendance != null ? `${s.attendance}%` : '', s.marks ?? '', s.gpa ?? '',
    format(new Date(s.enrollment_date), 'MMM d, yyyy'),
  ]);

  autoTable(doc, {
    head: [headers],
    body,
    startY: 28,
    theme: 'grid',
    styles: { fontSize: 7, cellPadding: 1.5 },
    headStyles: { fillColor: [80, 60, 160], textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: [245, 245, 255] },
    didDrawPage: (data) => {
      doc.setFontSize(7);
      doc.setTextColor(150);
      doc.text(
        `Page ${data.pageNumber} | Generated by Scholar AI`,
        data.settings.margin.left,
        doc.internal.pageSize.height - 8,
      );
    },
  });

  doc.save(`students_${format(new Date(), 'yyyy-MM-dd')}.pdf`);
}

export function StudentsListPage() {
  const [students, setStudents] = useState<Student[]>([]);
  const [loading, setLoading] = useState(true);
  const [showSignOutConfirm, setShowSignOutConfirm] = useState(false);
  const navigate = useNavigate();

  useEffect(() => {
    let active = true;

    supabase.auth.getSession().then(({ data }) => {
      const userId = data.session?.user.id;
      if (!userId) {
        if (active) {
          setLoading(false);
        }
        return;
      }

      supabase
        .from('students')
        .select('*')
        .eq('user_id', userId)
        .order('first_name')
        .then(({ data: students }) => {
          if (active) {
            setStudents(students ?? []);
            setLoading(false);
          }
        });
    });

    const channel = supabase
      .channel('students-list-live')
      .on('postgres_changes', { event: '*', schema: 'public', table: 'students' }, () => {
        supabase.auth.getSession().then(({ data }) => {
          const userId = data.session?.user.id;
          if (!userId) {
            return;
          }
          supabase
            .from('students')
            .select('*')
            .eq('user_id', userId)
            .order('first_name')
            .then(({ data: students }) => {
              if (active) {
                setStudents(students ?? []);
              }
            });
        });
      })
      .subscribe();

    return () => {
      active = false;
      supabase.removeChannel(channel);
    };
  }, []);

  async function handleSignOut() {
    await supabase.auth.signOut();
    navigate('/auth', { replace: true });
  }

  const stats = useMemo(() => ({
    total: students.length,
    active: students.filter((s) => s.status === 'active').length,
    departments: new Set(students.map((s) => s.department).filter(Boolean)).size,
  }), [students]);

  return (
    <div className="relative min-h-screen">
      <GeometricBackground />
      <div className="noise-overlay" />
      <div className="pointer-events-none fixed inset-0 -z-10 opacity-[0.03]"
        style={{
          backgroundImage: `
            linear-gradient(rgba(255,255,255,0.1) 1px, transparent 1px),
            linear-gradient(90deg, rgba(255,255,255,0.1) 1px, transparent 1px)
          `,
          backgroundSize: '60px 60px',
        }}
      />

      <header className="border-b border-white/[0.06] bg-white/[0.02] backdrop-blur-2xl animate-fade-down">
        <div className="mx-auto flex max-w-7xl items-center justify-between gap-4 px-6 py-4 lg:px-8">
          <Link to="/" className="flex items-center gap-3">
            <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-gradient-to-br from-primary/30 to-purple-600/20 border border-white/15 backdrop-blur-xl">
              <Users className="h-4 w-4 text-primary" />
            </div>
            <div className="hidden sm:block">
              <TextReveal
                text="Scholar"
                as="span"
                fontSize="0.875rem"
                color="hsl(var(--primary))"
                hoverColor="#b2c73a"
                staggerDelay={20}
                duration={200}
                className="font-semibold tracking-[0.24em] p-0 leading-normal"
              />
              <p className="text-xs text-muted-foreground">Student records</p>
            </div>
          </Link>
          <div className="flex items-center gap-2">
            <Tooltip>
              <TooltipTrigger asChild>
                <Button asChild variant="ghost" size="sm">
                  <Link to="/dashboard">Dashboard</Link>
                </Button>
              </TooltipTrigger>
              <TooltipContent side="bottom">Go to dashboard</TooltipContent>
            </Tooltip>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button variant="outline" size="sm" onClick={() => setShowSignOutConfirm(true)}>
                  <LogOut className="h-4 w-4" />
                  Sign out
                </Button>
              </TooltipTrigger>
              <TooltipContent side="bottom">Sign out of your account</TooltipContent>
            </Tooltip>
          </div>
        </div>
      </header>

      <main className="mx-auto max-w-7xl space-y-8 px-6 py-8 lg:px-8">
        <section className="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between animate-fade-up" style={{ animationDelay: '0.05s' }}>
          <div>
            <p className="text-sm font-medium text-primary">Student directory</p>
            <h1 className="mt-2 text-3xl font-semibold tracking-tight">List Of Students</h1>
            <p className="mt-2 max-w-2xl text-sm text-muted-foreground">
              View all student credentials and export records.
            </p>
          </div>
          <div className="flex gap-2">
            <Tooltip>
              <TooltipTrigger asChild>
                <Button variant="outline" onClick={() => exportToCSV(students)} disabled={students.length === 0}>
                  <FileSpreadsheet className="h-4 w-4" />
                  <span className="hidden sm:inline">Export CSV</span>
                </Button>
              </TooltipTrigger>
              <TooltipContent side="bottom">Export as CSV file</TooltipContent>
            </Tooltip>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button variant="outline" onClick={() => exportToJSON(students)} disabled={students.length === 0}>
                  <FileJson className="h-4 w-4" />
                  <span className="hidden sm:inline">Export JSON</span>
                </Button>
              </TooltipTrigger>
              <TooltipContent side="bottom">Export as JSON file</TooltipContent>
            </Tooltip>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button variant="outline" onClick={() => exportToPDF(students)} disabled={students.length === 0}>
                  <FileText className="h-4 w-4" />
                  <span className="hidden sm:inline">Export PDF</span>
                </Button>
              </TooltipTrigger>
              <TooltipContent side="bottom">Export as PDF document</TooltipContent>
            </Tooltip>
          </div>
        </section>

        <section className="grid gap-4 md:grid-cols-3 animate-fade-up" style={{ animationDelay: '0.08s' }}>
          <Card>
            <CardContent className="p-6">
              <p className="text-sm text-muted-foreground">Total Students</p>
              <p className="mt-2 text-3xl font-semibold tracking-tight">{loading ? '...' : stats.total}</p>
            </CardContent>
          </Card>
          <Card>
            <CardContent className="p-6">
              <p className="text-sm text-muted-foreground">Active</p>
              <p className="mt-2 text-3xl font-semibold tracking-tight">{loading ? '...' : stats.active}</p>
            </CardContent>
          </Card>
          <Card>
            <CardContent className="p-6">
              <p className="text-sm text-muted-foreground">Departments</p>
              <p className="mt-2 text-3xl font-semibold tracking-tight">{loading ? '...' : stats.departments}</p>
            </CardContent>
          </Card>
        </section>

        <section className="animate-fade-up" style={{ animationDelay: '0.1s' }}>
          <Card>
            <CardHeader>
              <CardTitle>All Students</CardTitle>
              <CardDescription>{students.length} record{students.length !== 1 ? 's' : ''}</CardDescription>
            </CardHeader>
            <CardContent className="p-0 sm:p-6 sm:pt-0">
              <div className="overflow-x-auto rounded-xl border border-white/[0.06]">
                <Table>
                  <TableHeader>
                    <TableRow>
                      <TableHead>USN</TableHead>
                      <TableHead>Name</TableHead>
                      <TableHead>Email</TableHead>
                      <TableHead>Phone</TableHead>
                      <TableHead>Department</TableHead>
                      <TableHead>Sem</TableHead>
                      <TableHead>Status</TableHead>
                      <TableHead>Grade</TableHead>
                      <TableHead>Attendance</TableHead>
                      <TableHead>Marks</TableHead>
                      <TableHead>GPA</TableHead>
                      <TableHead>Enrolled</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {loading ? (
                      <TableRow>
                        <TableCell colSpan={12} className="py-12 text-center text-muted-foreground">
                          Loading students...
                        </TableCell>
                      </TableRow>
                    ) : students.length === 0 ? (
                      <TableRow>
                        <TableCell colSpan={12} className="py-12 text-center text-muted-foreground">
                          No students found. Add some from the dashboard.
                        </TableCell>
                      </TableRow>
                    ) : (
                      students.map((student, index) => (
                        <TableRow key={student.id} className="animate-stagger-fast" style={{ animationDelay: `${index * 0.02}s` }}>
                          <TableCell className="font-mono text-xs">{student.usn || '\u2014'}</TableCell>
                          <TableCell className="font-medium">{student.first_name} {student.last_name}</TableCell>
                          <TableCell className="text-xs">{student.email || '\u2014'}</TableCell>
                          <TableCell className="text-xs">{student.phone || '\u2014'}</TableCell>
                          <TableCell>{student.department || '\u2014'}</TableCell>
                          <TableCell>{student.semester ?? '\u2014'}</TableCell>
                          <TableCell>
                            <Badge variant={statusStyles[student.status]}>{student.status}</Badge>
                          </TableCell>
                          <TableCell>{student.grade_level || '\u2014'}</TableCell>
                          <TableCell>{student.attendance ?? '\u2014'}{student.attendance != null ? '%' : ''}</TableCell>
                          <TableCell>{student.marks ?? '\u2014'}</TableCell>
                          <TableCell>{student.gpa ?? '\u2014'}</TableCell>
                          <TableCell className="text-xs">{format(new Date(student.enrollment_date), 'MMM d, yyyy')}</TableCell>
                        </TableRow>
                      ))
                    )}
                  </TableBody>
                </Table>
              </div>
            </CardContent>
          </Card>
        </section>
      </main>

      <AlertDialog
        open={showSignOutConfirm}
        onOpenChange={setShowSignOutConfirm}
        title="Sign out"
        description="Are you sure you want to sign out?"
        onConfirm={() => void handleSignOut()}
      />
    </div>
  );
}
